function StatusBadge({ status }: { status: MaterialStatus }) {
  const label =
    status === 'MATCHED'
      ? 'Matched'
      : status === 'REVIEW'
        ? 'Review'
        : 'Unmatched'

  return (
    <span className={`material-status material-status-${status.toLowerCase()}`}>
      {label}
    </span>
  )
}

