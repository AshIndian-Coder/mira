export default function Materials() {
  const [search, setSearch] = useState('')
  const [cpse, setCpse] = useState('All CPSEs')
  const [category, setCategory] = useState('All Categories')
  const [status, setStatus] = useState('All Statuses')
  const [selectedMaterial, setSelectedMaterial] = useState<Material | null>(
    null,
  )

  const filteredMaterials = useMemo(() => {
    const query = search.trim().toLowerCase()

    return materials.filter((material) => {
      const matchesSearch =
        !query ||
        material.code.toLowerCase().includes(query) ||
        material.description.toLowerCase().includes(query) ||
        material.cpse.toLowerCase().includes(query)

      const matchesCpse =
        cpse === 'All CPSEs' || material.cpse === cpse

      const matchesCategory =
        category === 'All Categories' || material.category === category

      const matchesStatus =
        status === 'All Statuses' ||
        material.status === status

      return (
        matchesSearch &&
        matchesCpse &&
        matchesCategory &&
        matchesStatus
      )
    })
  }, [search, cpse, category, status])

  return (
    <div className="page">
      <div className="page-header materials-page-header">
        <div>
          <div className="eyebrow">MATERIAL MASTER</div>
          <h1>Materials</h1>
          <p>
            View, inspect and prepare CPSE material records for harmonization.
          </p>
        </div>

        <button className="primary-button">
          Upload Material Data
        </button>
      </div>

      <div className="materials-summary">
        <div>
          <span>Total Records</span>
          <strong>43,301</strong>
        </div>

        <div>
          <span>CPSE Sources</span>
          <strong>6</strong>
        </div>

        <div>
          <span>Normalized</span>
          <strong>38,742</strong>
        </div>

        <div>
          <span>Pending Matching</span>
          <strong>326</strong>
        </div>
      </div>

      <div className="materials-card">
        <div className="materials-toolbar">
          <input
            className="materials-search"
            type="text"
            placeholder="Search material code, description or CPSE..."
            value={search}
            onChange={(event) => setSearch(event.target.value)}
          />

          <select value={cpse} onChange={(event) => setCpse(event.target.value)}>
            <option>All CPSEs</option>
            <option>IOCL</option>
            <option>ONGC</option>
            <option>BPCL</option>
            <option>NTPC</option>
            <option>SAIL</option>
            <option>BHEL</option>
          </select>

          <select
            value={category}
            onChange={(event) => setCategory(event.target.value)}
          >
            <option>All Categories</option>
            <option>Valves</option>
            <option>Fasteners</option>
            <option>Electrical</option>
          </select>

          <select
            value={status}
            onChange={(event) => setStatus(event.target.value)}
          >
            <option>All Statuses</option>
            <option value="MATCHED">Matched</option>
            <option value="REVIEW">Review</option>
            <option value="UNMATCHED">Unmatched</option>
          </select>
        </div>

        <div className="materials-table-wrapper">
          <table className="materials-table">
            <thead>
              <tr>
                <th>CPSE</th>
                <th>Material Code</th>
                <th>Description</th>
                <th>Category</th>
                <th>Material / Grade</th>
                <th>Size</th>
                <th>Status</th>
              </tr>
            </thead>

            <tbody>
              {filteredMaterials.map((material) => (
                <tr
                  key={`${material.cpse}-${material.code}`}
                  onClick={() => setSelectedMaterial(material)}
                >
                  <td>
                    <strong>{material.cpse}</strong>
                  </td>

                  <td>
                    <span className="material-code">
                      {material.code}
                    </span>
                  </td>

                  <td className="material-description">
                    {material.description}
                  </td>

                  <td>{material.category}</td>

                  <td>{material.material}</td>

                  <td>{material.size}</td>

                  <td>
                    <StatusBadge status={material.status} />
                  </td>
                </tr>
              ))}

              {filteredMaterials.length === 0 && (
                <tr>
                  <td colSpan={7} className="materials-empty">
                    No materials match the current filters.
                  </td>
                </tr>
              )}
            </tbody>
          </table>
        </div>

        <div className="materials-footer">
          Showing {filteredMaterials.length} of {materials.length} demo records
        </div>
      </div>

      {selectedMaterial && (
        <div
          className="material-detail-overlay"
          onClick={() => setSelectedMaterial(null)}
        >
          <div
            className="material-detail-modal"
            onClick={(event) => event.stopPropagation()}
          >
            <MaterialDetails
              material={selectedMaterial}
              onClose={() => setSelectedMaterial(null)}
            />
          </div>
        </div>
      )}
    </div>
  )
}
